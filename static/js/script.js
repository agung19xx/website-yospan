// ============================================================
// NORMALISASI NAMA GERAKAN
// ============================================================

function normalizeMovementName(label) {

    if (!label) {
        return null;
    }

    const normalized =
        label
            .toString()
            .trim()
            .toLowerCase()
            .replace(/_/g, " ")
            .replace(/-/g, " ")
            .replace(/\s+/g, " ");


    const movementMap = {

        "gale gale": "Gale-gale",

        "jef": "Jef",

        "pacul tiga": "Pacul Tiga",

        "pancar": "Pancar",

        "seka": "Seka"

    };


    return movementMap[normalized] || label;

}


