// ============================================================
// MENAMPILKAN GAMBAR TUTORIAL
// ============================================================

function renderTutorialImage() {

    const imageBox =
        document.getElementById(
            "tutorialImageBox"
        );


    if (!imageBox) {
        return;
    }


    const imageCandidates =
        tutorialImageMap[currentMovement];


    /*
       Jika mapping gambar tidak tersedia,
       langsung tampilkan fallback.
    */

    if (
        !imageCandidates ||
        imageCandidates.length === 0
    ) {

        showTutorialFallback(
            imageBox
        );

        return;
    }


    let currentCandidate = 0;


    function tryNextImage() {

        if (
            currentCandidate >=
            imageCandidates.length
        ) {

            showTutorialFallback(
                imageBox
            );

            return;
        }


        const image =
            new Image();


        const imagePath =
            imageCandidates[
                currentCandidate
            ];


        image.onload =
            function () {

                imageBox.innerHTML = `

                    <img
                        src="${imagePath}"
                        alt="Ilustrasi gerakan ${currentMovement}"
                        class="tutorial-image"
                    >

                `;

            };


        image.onerror =
            function () {

                currentCandidate++;

                tryNextImage();

            };


        image.src =
            imagePath;

    }


    tryNextImage();

}


// ============================================================
// FALLBACK GAMBAR
// ============================================================

function showTutorialFallback(imageBox) {

    imageBox.innerHTML = `

        <div class="tutorial-image-fallback">

            <span>
                Ilustrasi Gerakan
            </span>

            <small>
                Gambar untuk gerakan ${currentMovement}
                belum tersedia.
            </small>

        </div>

    `;

}


// ============================================================
// RENDER TUTORIAL
// ============================================================

function renderTutorial() {

    const steps =
        tutorialData[currentMovement];


    if (!steps) {
        return;
    }


    const step =
        steps[currentStep];


    // =========================================================
    // HEADER
    // =========================================================

    tutorialTitle.textContent =
        currentMovement;


    stepCounter.textContent =
        `Langkah ${currentStep + 1} dari ${steps.length}`;


    // =========================================================
    // STEP INDICATOR
    // =========================================================

    stepIndicator.innerHTML =
        "";


    steps.forEach(
        function (_, index) {

            const item =
                document.createElement("div");


            item.className =
                "step-dot";


            if (
                index ===
                currentStep
            ) {

                item.classList.add(
                    "active"
                );

            }


            item.textContent =
                index + 1;


            stepIndicator.appendChild(
                item
            );

        }
    );


    // =========================================================
    // KONTEN TUTORIAL
    // =========================================================

    tutorialContent.innerHTML = `

        <div
            class="tutorial-image-placeholder"
            id="tutorialImageBox"
        >

            <div class="tutorial-image-fallback">

                <span>
                    Memuat ilustrasi gerakan...
                </span>

            </div>

        </div>


        <div class="tutorial-text">

            <h3>
                ${step.title}
            </h3>


            <div class="tutorial-points">


                <div class="tutorial-point">

                    <strong>
                        Kepala / Pandangan
                    </strong>

                    <p>
                        ${step.head}
                    </p>

                </div>


                <div class="tutorial-point">

                    <strong>
                        Tangan
                    </strong>

                    <p>
                        ${step.hands}
                    </p>

                </div>


                <div class="tutorial-point">

                    <strong>
                        Badan
                    </strong>

                    <p>
                        ${step.body}
                    </p>

                </div>


                <div class="tutorial-point">

                    <strong>
                        Kaki
                    </strong>

                    <p>
                        ${step.feet}
                    </p>

                </div>


                <div class="tutorial-point">

                    <strong>
                        Arah Gerakan
                    </strong>

                    <p>
                        ${step.direction}
                    </p>

                </div>

            </div>

        </div>

    `;


    /*
       Gambar hanya berdasarkan currentMovement.

       currentStep TIDAK digunakan untuk memilih gambar.

       Jadi:
       Langkah 1  gambar Gale-gale
       Langkah 2  gambar Gale-gale
       Langkah 3  gambar Gale-gale

       dan seterusnya.
    */

    renderTutorialImage();


    // =========================================================
    // BUTTON SEBELUMNYA
    // =========================================================

    previousStep.disabled =
        currentStep === 0;


    // =========================================================
    // BUTTON SELANJUTNYA
    // =========================================================

    if (
        currentStep ===
        steps.length - 1
    ) {

        nextStep.textContent =
            "Langkah Terakhir";

        nextStep.disabled =
            true;

    } else {

        nextStep.textContent =
            "Langkah Selanjutnya ";

        nextStep.disabled =
            false;

    }

}


// ============================================================
// LANGKAH SEBELUMNYA
// ============================================================

if (previousStep) {

    previousStep.addEventListener(
        "click",
        function () {

            if (currentStep > 0) {

                currentStep--;

                renderTutorial();

            }

        }
    );

}


// ============================================================
// LANGKAH SELANJUTNYA
// ============================================================

if (nextStep) {

    nextStep.addEventListener(
        "click",
        function () {

            const steps =
                tutorialData[currentMovement];


            if (!steps) {
                return;
            }


            if (
                currentStep <
                steps.length - 1
            ) {

                currentStep++;

                renderTutorial();

            }

        }
    );

}


